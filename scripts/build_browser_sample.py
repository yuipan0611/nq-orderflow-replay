"""Build the browser's synthetic MBP-10 practice file without reading market data.

Requires databento-dbn and zstandard.
"""

from base64 import b64encode
from datetime import date, datetime, timedelta, timezone
import json
from pathlib import Path
from textwrap import wrap
from types import SimpleNamespace

import databento_dbn as dbn
import zstandard

DAY = date(2026, 1, 6)
START = datetime(2026, 1, 6, 14, 30, tzinfo=timezone.utc)
START_NS = int(START.timestamp()) * 1_000_000_000
END_SECONDS = 180
FIRST_SECONDS = -5
TICK = 250_000_000
CONTRACTS = {'NQH6': 42001, 'NQM6': 42002}
OUTPUT = Path(__file__).resolve().parents[1] / 'docs' / 'synthetic-dbn-sample.js'


def book(index, contract):
    if contract == 0:
        cycle = index % 60
        bid = 82400 + (index // 100) * 7 + min(cycle, 60 - cycle) // 2
        wall = 24 if 80 <= index % 200 < 170 else 0
    else:
        cycle = index % 96
        bid = 82520 + min(cycle, 96 - cycle) // 6
        wall = 10 if index % 180 < 90 else 0
    return [
        dbn.BidAskPair(
            bid_px=(bid - rank) * TICK,
            ask_px=(bid + 1 + rank) * TICK,
            bid_sz=5 + (index * 3 + rank * 5 + contract) % 18 + (wall if rank in (2, 3) else 0),
            ask_sz=6 + (index * 7 + rank * 3 + contract) % 19,
        )
        for rank in range(10)
    ]


def build():
    intervals = [
        SimpleNamespace(raw_symbol=symbol, intervals=[
            SimpleNamespace(start_date=DAY, end_date=DAY + timedelta(days=1), symbol=str(instrument))
        ])
        for symbol, instrument in CONTRACTS.items()
    ]
    meta = dbn.Metadata(
        dataset='GLBX.MDP3',
        start=START_NS + FIRST_SECONDS * 1_000_000_000,
        end=START_NS + (END_SECONDS + 1) * 1_000_000_000,
        stype_in=dbn.SType.RAW_SYMBOL,
        stype_out=dbn.SType.INSTRUMENT_ID,
        schema=dbn.Schema.MBP_10,
        symbols=list(CONTRACTS),
        mappings=intervals,
    )

    def message(instrument, ns, sequence, action, side, price, size, levels):
        return bytes(dbn.MBP10Msg(
            publisher_id=1, instrument_id=instrument, ts_event=ns, ts_recv=ns,
            price=price, size=size, action=action, side=side, depth=0, sequence=sequence, levels=levels,
        ))

    chunks = [bytes(meta)]
    sequence = 0
    for index, milliseconds in enumerate(range(FIRST_SECONDS * 1000, END_SECONDS * 1000 + 1, 250)):
        trades = []
        for contract, instrument in enumerate(CONTRACTS.values()):
            ns = START_NS + milliseconds * 1_000_000 + contract * 1000
            levels = book(index, contract)
            sequence += 1
            chunks.append(message(instrument, ns, sequence, dbn.Action.ADD if index == 0 else dbn.Action.MODIFY,
                                  dbn.Side.BID, levels[0].bid_px, levels[0].bid_sz, levels))
            if 0 <= milliseconds < END_SECONDS * 1000 and index % (3 if contract == 0 else 7) == 0:
                buy = (index // 3 + contract) % 4 != 0
                trades.append((instrument, ns + 40_000_000, dbn.Side.BID if buy else dbn.Side.ASK,
                               levels[0].ask_px if buy else levels[0].bid_px,
                               1 + (index + contract * 5) % 12, levels))
        for instrument, ns, side, price, size, levels in trades:
            sequence += 1
            chunks.append(message(instrument, ns, sequence, dbn.Action.TRADE, side, price, size, levels))
    return zstandard.ZstdCompressor(level=5).compress(b''.join(chunks))


def main():
    encoded = b64encode(build()).decode('ascii')
    fields = {
        'filename': 'synthetic-nq-classroom.mbp-10.dbn.zst',
        'start': START.strftime('%H:%M:%S'),
        'defaultEnd': (START + timedelta(minutes=1)).strftime('%H:%M:%S'),
        'end': (START + timedelta(seconds=END_SECONDS)).strftime('%H:%M:%S'),
    }
    lines = [f'  {key}: {json.dumps(value)},' for key, value in fields.items()]
    lines.extend(['  compressed: [', *(f'    "{part}",' for part in wrap(encoded, 100)), '  ].join(""),'])
    OUTPUT.write_text(
        '// Generated by scripts/build_browser_sample.py from synthetic market data.\n'
        'const NQ_CLASSROOM_SAMPLE = {\n' + '\n'.join(lines) + '\n};\n',
        encoding='ascii',
    )


if __name__ == '__main__':
    main()
